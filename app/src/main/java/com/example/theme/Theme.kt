val MemoDeckShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(20.dp),
    extraLarge = RoundedCornerShape(28.dp)
)

@Composable
fun MemoDeckTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM_DEFAULT,
    content: @Composable () -> Unit
) {
    val useDark = when (themeMode) {
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
        ThemeMode.SYSTEM_DEFAULT -> isSystemInDarkTheme()
    }

    val colorScheme = if (useDark) DarkColorScheme else LightColorScheme
    val semanticColors = if (useDark) {
        SemanticColors(
            success = StatusSuccessDark,
            successContainer = StatusSuccessContainerDark,
            danger = StatusDangerDark,
            dangerContainer = StatusDangerContainerDark,
            warning = StatusWarningDark,
            warningContainer = StatusWarningContainerDark
        )
    } else {
        SemanticColors(
            success = StatusSuccessLight,
            successContainer = StatusSuccessContainerLight,
            danger = StatusDangerLight,
            dangerContainer = StatusDangerContainerLight,
            warning = StatusWarningLight,
            warningContainer = StatusWarningContainerLight
        )
    }

    CompositionLocalProvider(LocalSemanticColors provides semanticColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = MemoDeckTypography,
            shapes = MemoDeckShapes,
            content = content
        )
    }
}
